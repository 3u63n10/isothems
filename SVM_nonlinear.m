% Sort each column independently to pair sorted values (makes data approximately linear along y=x, simplifying the boundary)
X = sort(X);  % Default: sort along dim=1 (columns), 'ascend' mode. You can add parameter like X = sort(X, 1, 'descend');

s = [repmat({'class0'}, 150, 1); repmat({'class1'}, 150, 1)];

% =========================
% Train Kernel SVM (RBF Kernel for Nonlinear Boundary)
% =========================
mdl = fitcsvm(X, s, 'KernelFunction', 'rbf', 'KernelScale', 'auto', 'BoxConstraint', Inf);

% Support Vectors
sv = X(mdl.IsSupportVector, :);

% =========================
% Prepare Grid for Decision Boundary
% =========================
x1 = linspace(min(X(:,1)) - 0.5, max(X(:,1)) + 0.5, 200);
x2 = linspace(min(X(:,2)) - 0.5, max(X(:,2)) + 0.5, 200);
[x1Grid, x2Grid] = meshgrid(x1, x2);
xGrid = [x1Grid(:), x2Grid(:)];

[~, scores] = predict(mdl, xGrid);

% =========================
% Groups
% =========================
